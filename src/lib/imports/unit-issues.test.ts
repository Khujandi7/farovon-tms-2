import { describe, expect, it } from "vitest";
import { parseUnitIssues } from "./unit-issues";

describe("parseUnitIssues", () => {
  it("извлекает исходные названия из сообщений строки", () => {
    expect(parseUnitIssues(["Подразделение «Департамент бройлерного направления» не найдено", "Отдел «Откорм» не найден"])).toEqual([
      { kind: "DEPARTMENT", name: "Департамент бройлерного направления" },
      { kind: "UNIT", name: "Откорм" },
    ]);
  });
  it("название с кавычками внутри сохраняется целиком", () => {
    expect(parseUnitIssues(["Подразделение «ОАО «Фаровон»» не найдено"])).toEqual([{ kind: "DEPARTMENT", name: "ОАО «Фаровон»" }]);
  });
  it("неоднозначные и посторонние сообщения не считаются «не найдено» (создавать нечего)", () => {
    expect(parseUnitIssues(["Подразделение «Склад» неоднозначно", "Отдел «Учёт» неоднозначен", "Совпадение неточное"])).toEqual([]);
  });
});
